struct CycleStep {
  int cycle;
  std::string phase;
  std::string responsibility;
  std::string observed_signals;
  std::string dpi_check;
};

struct ModuleSpec {
  std::string name;
  std::string concern;
  std::string top_module;
  std::string probe_module;
  std::string imp2_rtl;
  std::vector<std::string> vip_cases;
  std::vector<std::string> cycle_notes;
  bool latch_buffer;
  std::string probe_sv;
};

std::string read_text(const fs::path& path) {
  std::ifstream input(path);
  if (!input) {
    throw std::runtime_error("cannot read " + path.string());
  }
  std::ostringstream buffer;
  buffer << input.rdbuf();
  return buffer.str();
}

void write_text(const fs::path& path, const std::string& text) {
  fs::create_directories(path.parent_path());
  std::ofstream output(path);
  if (!output) {
    throw std::runtime_error("cannot write " + path.string());
  }
  output << text;
}

bool contains(const std::string& text, const std::string& needle) {
  return text.find(needle) != std::string::npos;
}

void require_contains(const std::string& text, const std::string& needle, const fs::path& path) {
  if (!contains(text, needle)) {
    throw std::runtime_error(path.string() + " is missing required text: " + needle);
  }
}

void validate_manifest_inputs(const fs::path& repo_root, const ModuleSpec& spec) {
  const fs::path ip_path = repo_root / "e1/e1-h1/ip" / (spec.name + ".json");
  const fs::path vip_path = repo_root / "e1/e1-h1/vip" / (spec.name + ".json");
  const std::string ip = read_text(ip_path);
  const std::string vip = read_text(vip_path);

  require_contains(ip, "\"schema\": \"e1-h1-ip-v0\"", ip_path);
  require_contains(ip, "\"name\": \"" + spec.name + "\"", ip_path);
  require_contains(ip, "\"module\": \"" + spec.top_module + "\"", ip_path);
  require_contains(ip, "\"rtl\": \"" + spec.imp2_rtl + "\"", ip_path);
  require_contains(ip, "\"active\": \"imp2\"", ip_path);
  require_contains(ip, "\"reference\": \"imp1\"", ip_path);
  require_contains(ip, "\"acceptance\": \"verilator_dpi_vip_equivalent_to_imp1\"", ip_path);

  require_contains(vip, "\"schema\": \"e1-h1-module-vip-v0\"", vip_path);
  require_contains(vip, "\"name\": \"" + spec.name + "\"", vip_path);
  require_contains(vip, "\"top_module\": \"" + spec.top_module + "\"", vip_path);
  require_contains(vip, "\"rtl\": \"" + spec.imp2_rtl + "\"", vip_path);
  require_contains(vip, "\"kind\": \"module_only\"", vip_path);
  require_contains(vip, "\"allowed_systemverilog_modules\"", vip_path);
  require_contains(vip, "\"" + spec.top_module + "\"", vip_path);
  require_contains(vip, "\"neighbors\": \"cpp_environment\"", vip_path);
  for (const std::string& vip_case : spec.vip_cases) {
    require_contains(vip, "\"" + vip_case + "\"", vip_path);
  }
}

