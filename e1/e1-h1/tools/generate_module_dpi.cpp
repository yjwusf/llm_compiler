std::string vip_case_calls(const ModuleSpec& spec) {
  std::ostringstream out;
  for (const std::string& vip_case : spec.vip_cases) {
    out << "    e1_h1_module_dpi_case(\"" << spec.name << "\", \"" << vip_case << "\");\n";
  }
  return out.str();
}

std::string probe_sv_with_vip_cases(const ModuleSpec& spec) {
  std::string sv = spec.probe_sv;
  const std::string begin_import =
      "  import \"DPI-C\" function void e1_h1_module_dpi_begin(input string module_name, input string vip_case);\n";
  const std::string cycle_import =
      "  import \"DPI-C\" function void e1_h1_module_dpi_cycle(input string module_name, input int cycle, input string phase);\n";
  const std::size_t import_pos = sv.find(begin_import);
  if (import_pos == std::string::npos) {
    throw std::runtime_error(spec.name + " probe is missing DPI begin import");
  }
  sv.insert(import_pos + begin_import.size(), vip_case_import_line());

  const std::size_t cycle_import_pos = sv.find(cycle_import);
  if (cycle_import_pos == std::string::npos) {
    throw std::runtime_error(spec.name + " probe is missing DPI cycle import");
  }
  sv.insert(cycle_import_pos + cycle_import.size(), phase_signal_import_line());

  const std::string logic_anchor = "  logic clk_i;\n";
  const std::size_t logic_pos = sv.find(logic_anchor);
  if (logic_pos == std::string::npos) {
    throw std::runtime_error(spec.name + " probe is missing clk_i declaration");
  }
  sv.insert(logic_pos, "  logic [7:0] probe_cycle_phase_o;\n");

  const std::string begin_call = "    e1_h1_module_dpi_begin(\"" + spec.name + "\"";
  const std::size_t begin_pos = sv.find(begin_call);
  if (begin_pos == std::string::npos) {
    throw std::runtime_error(spec.name + " probe is missing DPI begin call");
  }
  const std::size_t line_end = sv.find('\n', begin_pos);
  if (line_end == std::string::npos) {
    throw std::runtime_error(spec.name + " probe has malformed DPI begin call");
  }
  sv.insert(line_end + 1, vip_case_calls(spec));

  const std::string cycle_call =
      "      e1_h1_module_dpi_cycle(\"" + spec.name + "\", cycle, phase_name(cycle));";
  const std::string phase_call =
      "      probe_cycle_phase_o = cycle[7:0];\n"
      "      e1_h1_module_dpi_cycle(\"" + spec.name + "\", cycle, phase_name(cycle));\n"
      "      if (e1_h1_module_dpi_phase_signal(\"" + spec.name +
      "\", \"probe_cycle_phase_o\", cycle, cycle, int'(probe_cycle_phase_o)) == 0) begin\n"
      "        $fatal(1, \"" + spec.name + " phase signal mismatch cycle %0d\", cycle);\n"
      "      end";
  std::size_t cycle_pos = 0;
  int replacements = 0;
  while ((cycle_pos = sv.find(cycle_call, cycle_pos)) != std::string::npos) {
    sv.replace(cycle_pos, cycle_call.size(), phase_call);
    cycle_pos += phase_call.size();
    ++replacements;
  }
  if (replacements != 1) {
    throw std::runtime_error(spec.name + " probe phase signal injection expected one cycle call");
  }
  return sv;
}

std::string main_cpp(const ModuleSpec& spec) {
  std::ostringstream out;
  out << "// SPDX-License-Identifier: Apache-2.0\n";
  out << "// Generated by e1/e1-h1/tools/generate_module_dpi.cpp.\n\n";
  out << "#include \"V" << spec.probe_module << ".h\"\n";
  out << "#include \"verilated.h\"\n\n";
  out << "int main(int argc, char** argv) {\n";
  out << "  VerilatedContext context;\n";
  out << "  context.commandArgs(argc, argv);\n";
  out << "  V" << spec.probe_module << " top{&context};\n";
  out << "  while (!context.gotFinish() && context.time() < 1000) {\n";
  out << "    top.eval();\n";
  out << "    context.timeInc(1);\n";
  out << "  }\n";
  out << "  return context.gotFinish() ? 0 : 1;\n";
  out << "}\n";
  return out.str();
}

