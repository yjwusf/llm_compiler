int probe_instantiation_count(const ModuleSpec& spec, const std::string& module_name) {
  return count_substring(spec.probe_sv, "\n  " + module_name + " u_") +
         count_substring(spec.probe_sv, "\n  " + module_name + " #(");
}

int probe_dut_instantiation_count(const ModuleSpec& spec) {
  return probe_instantiation_count(spec, spec.top_module);
}

int probe_reference_instantiation_count(const ModuleSpec& spec) {
  return probe_instantiation_count(spec, reference_module(spec));
}

void write_signal_array_json(std::ostringstream& out,
                             const std::string& key,
                             const std::vector<SignalSpec>& signals,
                             const std::string& indent) {
  out << indent << "\"" << key << "\": [";
  if (!signals.empty()) {
    out << "\n";
  }
  for (std::size_t i = 0; i < signals.size(); ++i) {
    const SignalSpec& signal = signals[i];
    out << indent << "  {\"name\": \"" << signal.name << "\", \"width\": \"" << signal.width
        << "\", \"description\": \"" << signal.description << "\"}"
        << (i + 1 == signals.size() ? "\n" : ",\n");
  }
  out << indent << "]";
}

void write_string_array_json(std::ostringstream& out,
                             const std::string& key,
                             const std::vector<std::string>& values,
                             const std::string& indent) {
  out << indent << "\"" << key << "\": [";
  for (std::size_t i = 0; i < values.size(); ++i) {
    out << (i == 0 ? "" : ", ") << "\"" << values[i] << "\"";
  }
  out << "]";
}

