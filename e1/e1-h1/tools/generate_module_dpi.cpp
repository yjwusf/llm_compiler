  out << "  initial begin\n";
  out << "    e1_h1_module_dpi_begin(\"" << module_name << "\", \"module_only_config_sram\");\n";
  out << "    clk_i = 1'b0;\n";
  out << "    rst_ni = 1'b0;\n";
  out << "    tick();\n";
  out << "    check_initialized(-1);\n";
  out << "    rst_ni = 1'b1;\n";
