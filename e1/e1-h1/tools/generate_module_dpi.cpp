std::string reference_sv_text(const fs::path& repo_root, const ModuleSpec& spec) {
  const fs::path source_path = repo_root / "e1/e1-h1/dpi/e1_h1_imp1_reference.sv";
  const std::string source_text = read_text(source_path);
  const std::string module_name = reference_module(spec);
  const std::string module_start_needle = "module " + module_name;
  const std::size_t module_start = source_text.find(module_start_needle);
  if (module_start == std::string::npos) {
    throw std::runtime_error(source_path.string() + " is missing module " + module_name);
  }
  const std::size_t endmodule_start = source_text.find("\nendmodule", module_start);
  if (endmodule_start == std::string::npos) {
    throw std::runtime_error(source_path.string() + " has no endmodule for " + module_name);
  }
  const std::size_t endmodule_line_end = source_text.find('\n', endmodule_start + 1);
  const std::size_t module_end =
      endmodule_line_end == std::string::npos ? source_text.size() : endmodule_line_end;
  std::ostringstream out;
  out << "`default_nettype none\n\n";
  out << source_text.substr(module_start, module_end - module_start) << "\n\n";
  out << "`default_nettype wire\n";
  return out.str();
}

std::string flist_text(const fs::path& probe, const ModuleSpec& spec) {
  std::ostringstream out;
  out << reference_rtl_path(spec) << "\n";
  out << spec.imp2_rtl << "\n";
  out << probe.generic_string() << "\n";
  return out.str();
}

std::vector<std::string> allowed_verification_modules(const ModuleSpec& spec) {
  return {reference_module(spec), spec.top_module};
}

std::vector<std::string> forbidden_design_neighbors(const ModuleSpec& spec) {
  std::vector<std::string> forbidden;
  for (const std::string& module : known_design_modules()) {
    if (module != spec.top_module) {
      forbidden.push_back(module);
    }
  }
  return forbidden;
}

int count_substring(const std::string& text, const std::string& needle) {
  int count = 0;
  std::size_t pos = 0;
  while ((pos = text.find(needle, pos)) != std::string::npos) {
    ++count;
    pos += needle.size();
  }
  return count;
}

